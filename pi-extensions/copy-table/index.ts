/**
 * copy-table: Interactive "Copy" buttons next to markdown tables
 *
 * Features:
 * - Clickable "📋 Copy" button rendered after each markdown table (OSC 8 hyperlink)
 * - Alt+Shift+C shortcut to copy the most recent table directly to clipboard
 * - /copy-table command to interactively select and copy a table
 * - Tables get AI-generated short names (cached on disk) for the picker
 */

import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { Box, Container, type SelectItem, SelectList, Text } from "@earendil-works/pi-tui";
import { DynamicBorder } from "@earendil-works/pi-coding-agent";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { appendFileSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";

// ---------------------------------------------------------------------------
// Clipboard helpers
// ---------------------------------------------------------------------------

function getClipboardCommand(): { cmd: string; args?: string[] } | null {
  switch (process.platform) {
    case "darwin":
      return { cmd: "pbcopy" };
    case "linux": {
      if (process.env.WAYLAND_DISPLAY || process.env.XDG_SESSION_TYPE === "wayland") {
        return { cmd: "wl-copy" };
      }
      return { cmd: "xclip", args: ["-selection", "clipboard"] };
    }
    case "win32":
      return { cmd: "clip" };
    default:
      return null;
  }
}

function copyToClipboard(text: string): boolean {
  const clip = getClipboardCommand();
  if (!clip) return false;
  try {
    const result = spawnSync(clip.cmd, clip.args ?? [], {
      input: text,
      stdio: ["pipe", "ignore", "pipe"],
      timeout: 3000,
    });
    return result.status === 0;
  } catch {
    return false;
  }
}

// ---------------------------------------------------------------------------
// Table detection
// ---------------------------------------------------------------------------

const TABLE_LINE_RE = /^\s*\|.+\|\s*$/;
const TABLE_SEPARATOR_RE = /^\s*\|[\s\-:]+(\|[\s\-:]+\|?)+\s*$/;

interface DetectedTable {
  startLine: number;
  endLine: number;
  table: string;
}

function findMarkdownTables(markdown: string): DetectedTable[] {
  const lines = markdown.split("\n");
  const tables: DetectedTable[] = [];
  let inCodeBlock = false;
  let tableStart = -1;

  for (let i = 0; i < lines.length; i++) {
    const trimmed = lines[i].trimStart();
    if (trimmed.startsWith("```")) {
      inCodeBlock = !inCodeBlock;
      if (tableStart !== -1) tableStart = -1;
      continue;
    }
    if (inCodeBlock) continue;

    if (TABLE_LINE_RE.test(lines[i])) {
      if (tableStart === -1) tableStart = i;
    } else if (tableStart !== -1) {
      maybeFlushTable(lines, tableStart, i - 1, tables);
      tableStart = -1;
    }
  }
  if (tableStart !== -1) {
    maybeFlushTable(lines, tableStart, lines.length - 1, tables);
  }
  return tables;
}

function maybeFlushTable(
  lines: string[],
  start: number,
  end: number,
  tables: DetectedTable[],
): void {
  const slice = lines.slice(start, end + 1);
  const hasSep = slice.some((l) => TABLE_SEPARATOR_RE.test(l));
  if (hasSep && slice.length >= 3) {
    tables.push({ startLine: start, endLine: end, table: slice.join("\n") });
  }
}

// ---------------------------------------------------------------------------
// AI table naming (background, cached on disk)
// ---------------------------------------------------------------------------

/**
 * Names are generated by a small fast model and cached on disk, so tables
 * keep their names across restarts and resumed sessions.
 *
 * Model picked by benchmarks/copy-table-naming (2026-08-19): nemotron-3-ultra
 * had the tightest latency tail of every Fireworks serverless model (p90 507ms,
 * max 530ms over 17 tables) with near-best names.
 *
 * NOTE: it is a reasoning model — without `reasoning_effort: "none"` it spends
 * the whole token budget on `reasoning_content` and returns an empty `content`.
 */
const NAMING_ENDPOINT = "https://api.fireworks.ai/inference/v1/chat/completions";
const NAMING_MODEL =
  process.env.PI_COPY_TABLE_MODEL ||
  "accounts/fireworks/models/nemotron-3-ultra-nvfp4";
const CACHE_PATH = `${homedir()}/.pi/agent/copy-table-names.json`;
const DEBUG = Boolean(process.env.PI_COPY_TABLE_DEBUG);

function log(msg: string): void {
  if (!DEBUG) return;
  try {
    appendFileSync("/tmp/pi-copy-table.log", `[${new Date().toISOString()}] ${msg}\n`);
  } catch {
    // Logging must never break naming
  }
}

function tableKey(table: string): string {
  return createHash("sha256").update(table).digest("hex").slice(0, 16);
}

/** Disk-backed cache: table hash → AI-generated short name. */
let nameCache: Map<string, string> | null = null;

function getCache(): Map<string, string> {
  if (nameCache) return nameCache;
  nameCache = new Map();
  try {
    const raw = JSON.parse(readFileSync(CACHE_PATH, "utf8"));
    for (const [k, v] of Object.entries(raw)) {
      if (typeof v === "string") nameCache.set(k, v);
    }
  } catch {
    // No cache file yet
  }
  return nameCache;
}

function persistCache(): void {
  try {
    writeFileSync(CACHE_PATH, JSON.stringify(Object.fromEntries(getCache()), null, 2));
  } catch (err: any) {
    log(`cache write failed: ${err?.message || err}`);
  }
}

function getCachedName(table: string): string | undefined {
  return getCache().get(tableKey(table));
}

function sanitizeName(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const name = raw
    .split("\n")[0]
    .trim()
    .replace(/^["'`*]+|["'`*.]+$/g, "")
    .trim()
    .slice(0, 48);
  return name || null;
}

/** Read the fireworks API key synchronously from pi's auth.json. */
function resolveNamingApiKey(): string | null {
  if (process.env.FIREWORKS_API_KEY) return process.env.FIREWORKS_API_KEY;
  try {
    const auth = JSON.parse(readFileSync(`${homedir()}/.pi/agent/auth.json`, "utf8"));
    return auth?.fireworks?.key || null;
  } catch {
    return null;
  }
}

/** In-flight requests, so the same table is never named twice concurrently. */
const pending = new Map<string, Promise<string | null>>();

function nameTable(table: string, apiKey: string): Promise<string | null> {
  const key = tableKey(table);
  const cached = getCache().get(key);
  if (cached) return Promise.resolve(cached);
  const inflight = pending.get(key);
  if (inflight) return inflight;

  const request = (async (): Promise<string | null> => {
    try {
      const resp = await fetch(NAMING_ENDPOINT, {
        method: "POST",
        headers: {
          Authorization: `Bearer ${apiKey}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          model: NAMING_MODEL,
          messages: [
            {
              role: "user",
              content:
                `Give a 2-4 word descriptive name for this table. ` +
                `Reply ONLY with the name, no explanation, no quotes:\n\n` +
                table.slice(0, 600),
            },
          ],
          max_tokens: 24,
          temperature: 0,
          reasoning_effort: "none",
        }),
        signal: AbortSignal.timeout(8000),
      });
      const body = await resp.text();
      if (!resp.ok) {
        log(`${key}: HTTP ${resp.status} ${body.slice(0, 200)}`);
        return null;
      }
      let data: any;
      try {
        data = JSON.parse(body);
      } catch {
        log(`${key}: unparseable response ${body.slice(0, 200)}`);
        return null;
      }
      const name = sanitizeName(data?.choices?.[0]?.message?.content);
      if (!name) {
        log(`${key}: empty content ${body.slice(0, 300)}`);
        return null;
      }
      getCache().set(key, name);
      persistCache();
      log(`${key}: named "${name}"`);
      return name;
    } catch (err: any) {
      log(`${key}: request failed: ${err?.message || err}`);
      return null;
    } finally {
      pending.delete(key);
    }
  })();

  pending.set(key, request);
  return request;
}

/** Name every table (cached ones resolve instantly). Never rejects. */
function nameTables(tables: string[]): Promise<(string | null)[]> {
  const apiKey = resolveNamingApiKey();
  if (!apiKey) {
    log("no fireworks API key in auth.json / $FIREWORKS_API_KEY — skipping naming");
    return Promise.resolve(tables.map(() => null));
  }
  return Promise.all(tables.map((t) => nameTable(t, apiKey).catch(() => null)));
}

// ---------------------------------------------------------------------------
// Markdown → TSV conversion
// ---------------------------------------------------------------------------

/**
 * Convert a markdown table string to TSV (tab-separated values).
 * Strips pipes, trims cell whitespace, skips the separator row.
 *
 * Input:
 *   | Name | Age |
 *   |------|-----|
 *   | Alice | 30 |
 *
 * Output:
 *   Name\tAge
 *   Alice\t30
 */
function markdownTableToTsv(mdTable: string): string {
  const lines = mdTable.split("\n");
  const rows: string[] = [];

  for (const line of lines) {
    const trimmed = line.trim();
    // Skip separator lines (only contain |, -, :, and whitespace)
    if (/^\|[-:\s|]+\|$/.test(trimmed)) continue;
    // Strip leading/trailing pipe, split on |, trim each cell
    const inner = trimmed.replace(/^\|/, "").replace(/\|$/, "");
    const cells = inner.split("|").map((c) => c.trim());
    rows.push(cells.join("\t"));
  }

  return rows.join("\n");
}

// ---------------------------------------------------------------------------
// Markdown transformer — subtle text hint after tables
// ---------------------------------------------------------------------------

function addCopyHints(markdown: string): string {
  const tables = findMarkdownTables(markdown);
  if (tables.length === 0) return markdown;

  const lines = markdown.split("\n");
  for (let i = tables.length - 1; i >= 0; i--) {
    const t = tables[i];
    const insertAt = t.endLine + 1;
    const hint = `\n> 📋 **Copy as TSV** — Alt+Shift+C or /copy-table`;
    lines.splice(insertAt, 0, ...hint.split("\n"));
  }
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Session table extraction (for shortcut and command)
// ---------------------------------------------------------------------------

interface TableEntry {
  entryId: string;
  messageIndex: number;
  table: string;
  headerLine: string;
}

function extractTablesFromSession(ctx: {
  sessionManager: { getBranch(): any[] };
}): TableEntry[] {
  const entries = ctx.sessionManager.getBranch();
  const tables: TableEntry[] = [];

  for (const entry of entries) {
    if (entry.type !== "message" || entry.message?.role !== "assistant") continue;
    const content = entry.message.content;
    if (!Array.isArray(content)) continue;

    for (const block of content) {
      if (block.type !== "text" || typeof block.text !== "string") continue;
      const found = findMarkdownTables(block.text);
      for (let i = 0; i < found.length; i++) {
        const t = found[i];
        const headerLine =
          t.table.split("\n")[0]?.replace(/\s+/g, " ").trim().slice(0, 60) ?? "";
        tables.push({
          entryId: entry.id,
          messageIndex: i + 1,
          table: t.table,
          headerLine: headerLine + (headerLine.length >= 60 ? "…" : ""),
        });
      }
    }
  }
  return tables;
}

// ---------------------------------------------------------------------------
// Extension entry point
// ---------------------------------------------------------------------------

export default function (pi: ExtensionAPI) {
  // --- Entry renderer: styled copy button after tables ---
  // OSC 8 hyperlinks don't work inside Zellij, so the button is
  // visual-only. Interaction is via keyboard shortcut (Alt+Shift+C).
  pi.registerEntryRenderer("copy-table-btn", (entry, _opts, theme) => {
    const box = new Box(1, 0, (s: string) => theme.bg("toolPendingBg", s));
    const label =
      theme.fg("accent", "📋 Copy") +
      theme.fg("dim", " — Alt+Shift+C or /copy-table");
    box.addChild(new Text(label, 0, 0));
    return box;
  });

  // --- message_end: detect tables, append buttons, and kick off AI naming ---
  pi.on("message_end", (event, _ctx) => {
    const msg = event.message;
    if (!msg || msg.role !== "assistant") return;

    const content = msg.content;
    if (!Array.isArray(content)) return;

    const allTables: string[] = [];
    for (const block of content) {
      if (block.type !== "text" || typeof block.text !== "string") continue;
      const tables = findMarkdownTables(block.text);
      for (const t of tables) {
        pi.appendEntry("copy-table-btn", { table: t.table });
        allTables.push(t.table);
      }
    }

    // Fire-and-forget: name tables in background (populates the name cache)
    if (allTables.length > 0) {
      void nameTables(allTables);
    }
  });

  // --- Markdown transformer: fallback text hint (TUI-display-only) ---
  pi.registerMarkdownTransformer((markdown, { isStreaming, messageType }) => {
    if (isStreaming || messageType !== "assistant") return markdown;
    return addCopyHints(markdown);
  });

  // --- Command: /copy-table — interactive table selection ---
  pi.registerCommand("copy-table", {
    description: "Select and copy a markdown table from the conversation",
    handler: async (_args, ctx) => {
      if (!ctx.hasUI) return;

      const tableEntries = extractTablesFromSession(ctx);
      if (tableEntries.length === 0) {
        ctx.ui.notify("No markdown tables found in the conversation", "warning");
        return;
      }

      if (tableEntries.length === 1) {
        if (copyToClipboard(markdownTableToTsv(tableEntries[0].table))) {
          ctx.ui.notify("Table copied to clipboard as TSV", "info");
        } else {
          ctx.ui.notify("Failed to copy — no clipboard command available", "error");
        }
        return;
      }

      // Name any tables missing from the cache (e.g. a resumed session),
      // waiting briefly so the picker still opens fast.
      const missing = tableEntries
        .map((t) => t.table)
        .filter((table) => !getCachedName(table));
      if (missing.length > 0) {
        await Promise.race([
          nameTables(missing),
          new Promise((resolve) => setTimeout(resolve, 2500)),
        ]);
      }

      // Use AI-generated names from cache, fall back to "Table N"
      const names = tableEntries.map(
        (t, i) => getCachedName(t.table) || `Table ${i + 1}`,
      );
      const items: SelectItem[] = tableEntries.map((t, i) => ({
        value: String(i),
        label: names[i],
        description: t.headerLine,
      }));

      const selected = await ctx.ui.custom<string | null>(
        (tui, theme, _kb, done) => {
          const container = new Container();
          container.addChild(
            new DynamicBorder((s: string) => theme.fg("accent", s)),
          );
          container.addChild(
            new Text(theme.fg("accent", theme.bold("Copy Table to Clipboard")), 1, 0),
          );

          const selectList = new SelectList(items, Math.min(items.length, 12), {
            selectedPrefix: (t: string) => theme.fg("accent", t),
            selectedText: (t: string) => theme.fg("accent", t),
            description: (t: string) => theme.fg("muted", t),
            scrollInfo: (t: string) => theme.fg("dim", t),
            noMatch: (t: string) => theme.fg("warning", t),
          });
          selectList.onSelect = (item) => done(item.value);
          selectList.onCancel = () => done(null);
          container.addChild(selectList);

          container.addChild(
            new Text(
              theme.fg("dim", "↑↓ navigate • enter copy • esc cancel • / search"),
              1, 0,
            ),
          );
          container.addChild(
            new DynamicBorder((s: string) => theme.fg("accent", s)),
          );

          return {
            render: (w: number) => container.render(w),
            invalidate: () => container.invalidate(),
            handleInput: (data: string) => {
              selectList.handleInput(data);
              tui.requestRender();
            },
          };
        },
      );

      if (selected === null) return;

      const idx = parseInt(selected, 10);
      const entry = tableEntries[idx];
      if (!entry) return;

      if (copyToClipboard(markdownTableToTsv(entry.table))) {
        ctx.ui.notify("Table copied to clipboard as TSV", "info");
      } else {
        ctx.ui.notify("Failed to copy — no clipboard command available", "error");
      }
    },
  });

  // --- Shortcut: Alt+Shift+C — copy most recent table ---
  pi.registerShortcut("alt+shift+c", {
    description: "Copy the most recent markdown table to clipboard",
    handler: async (ctx) => {
      if (!ctx.hasUI) return;

      const tableEntries = extractTablesFromSession(ctx);
      if (tableEntries.length === 0) {
        ctx.ui.notify("No markdown tables in the conversation", "warning");
        return;
      }

      const last = tableEntries[tableEntries.length - 1];
      if (copyToClipboard(markdownTableToTsv(last.table))) {
        ctx.ui.notify("Table copied to clipboard as TSV", "info");
      } else {
        ctx.ui.notify("Failed to copy — no clipboard command available", "error");
      }
    },
  });
}
